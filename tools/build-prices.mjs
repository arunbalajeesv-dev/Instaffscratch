// Reads data/instaff_prices_v1.csv and writes app/prices.js, which sets window.INSTAFF_PRICES.
//
//   node tools/build-prices.mjs [path/to/prices.csv]
//
// Columns: service_id, item_key, value, item, charged_per.
// Items are matched in the app by service_id and item_key only, never by the "item" label.
//   service_id "_all"          whole-app settings
//   item_key "setting.<name>"  a setting (value stays text, blank stays blank)
//   item_key "question.<name>" a Y/N answer (true / false)
//   anything else              a price in rupees (a number)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const csvPath = resolve(process.argv[2] || resolve(root, 'data/instaff_prices_v1.csv'));
const outPath = resolve(root, 'app/prices.js');
const EXPECTED = ['service_id', 'item_key', 'value', 'item', 'charged_per'];

// A small CSV reader that understands quoted fields, doubled quotes and commas or line breaks inside quotes.
function parseCsv(text){
  const rows = []; let row = [], cell = '', quoted = false;
  for (let i = 0; i < text.length; i++){
    const c = text[i];
    if (quoted){
      if (c === '"'){ if (text[i + 1] === '"'){ cell += '"'; i++; } else quoted = false; }
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ','){ row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r'){
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cell); cell = ''; rows.push(row); row = [];
    } else cell += c;
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row); }
  return rows.filter(r => r.some(x => x.trim() !== ''));
}

const rows = parseCsv(readFileSync(csvPath, 'utf8').replace(/^﻿/, ''));
const header = rows.shift().map(h => h.trim());
if (header.join(',') !== EXPECTED.join(',')){
  console.error(`Unexpected columns: ${header.join(', ')}\nExpected:           ${EXPECTED.join(', ')}`);
  process.exit(1);
}

const out = {version: 'v1', source: 'data/instaff_prices_v1.csv', all: {settings: {}}, services: {}};
const seen = new Set(), problems = [];
const svc = id => (out.services[id] = out.services[id] || {items: {}, settings: {}, questions: {}});

rows.forEach((r, i) => {
  const [service_id, item_key, value] = [r[0], r[1], r[2]].map(x => (x || '').trim());
  const line = i + 2;
  if (!service_id || !item_key){ problems.push(`line ${line}: service_id and item_key are both required`); return; }
  const id = service_id + '|' + item_key;
  if (seen.has(id)) problems.push(`line ${line}: duplicate ${service_id} / ${item_key}`);
  seen.add(id);

  if (item_key.startsWith('setting.')){
    const name = item_key.slice('setting.'.length);
    (service_id === '_all' ? out.all.settings : svc(service_id).settings)[name] = value;
  } else if (item_key.startsWith('question.')){
    if (!/^[YN]$/i.test(value)){ problems.push(`line ${line}: ${item_key} must be Y or N, found "${value}"`); return; }
    svc(service_id).questions[item_key.slice('question.'.length)] = value.toUpperCase() === 'Y';
  } else {
    if (service_id === '_all'){ problems.push(`line ${line}: _all can only hold settings`); return; }
    const n = Number(value);
    if (value === '' || !Number.isFinite(n) || n < 0){ problems.push(`line ${line}: ${service_id} / ${item_key} has no valid price ("${value}"), so it will show "Price confirmed on call"`); svc(service_id); return; }
    svc(service_id).items[item_key] = n;
  }
});

writeFileSync(outPath,
  '// Generated by tools/build-prices.mjs from data/instaff_prices_v1.csv. Do not edit by hand.\n' +
  'window.INSTAFF_PRICES = ' + JSON.stringify(out, null, 1) + ';\n');

const counts = Object.values(out.services).reduce((a, s) => a + Object.keys(s.items).length, 0);
console.log(`Wrote ${outPath}\n${Object.keys(out.services).length} services, ${counts} prices, ${seen.size} rows read.`);
if (problems.length){ console.warn('\nCheck these rows:\n- ' + problems.join('\n- ')); process.exitCode = problems.some(p => /duplicate|required|must be|only hold/.test(p)) ? 1 : 0; }
